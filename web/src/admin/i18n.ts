const saved = (() => {
  try {
    return localStorage.getItem('bb.admin-locale')
  } catch {
    return null
  }
})()

export const i18n = createI18n({
  legacy: false,
  locale:
    saved === 'en' || saved === 'ru' ? saved : navigator.language.startsWith('ru') ? 'ru' : 'en',
  fallbackLocale: 'en',
  messages: { ru, en },
  pluralRules: {
    ru: (choice: number) => {
      if (choice === 0) return 0
      const mod10 = choice % 10
      const mod100 = choice % 100
      if (mod10 === 1 && mod100 !== 11) return 1
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 2
      return 3
    },
  },
})

export function setAdminLocale(locale: 'ru' | 'en'): void {
  i18n.global.locale.value = locale
  document.documentElement.lang = locale
  try {
    localStorage.setItem('bb.admin-locale', locale)
  } catch {
    // Not critical: the language just won't be remembered.
  }
}
